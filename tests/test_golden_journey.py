def _hooks(smoke_text: str = _SMOKE_OK, smoke_code: int = 0):
    def smoke():
        print(smoke_text, end="")
        return smoke_code

    return {
        "smoke_fn": smoke,
        "ready_fn": lambda _s: Check("A8", True, "fixture"),
        "session_fn": lambda _s, cap: gate_agrees_with_session(
            {"shipped": True}, {"status": "complete"}
        ),
        "pr_body_fn": lambda _c: pr_maps_requirement_to_change_to_test(
            "## Requirement\nr\n\n## Change\nc\n\n## Test\nt\n"
        ),
    }


def test_five_consecutive_mocked_journeys_pass():
    assert run_consecutive(5, **_hooks()) == 0


def test_consecutive_stops_on_first_failure():
    calls = {"n": 0}

    def smoke():
        calls["n"] += 1
        print(_SMOKE_OK, end="")
        return 1 if calls["n"] == 2 else 0

    hooks = _hooks()
    hooks["smoke_fn"] = smoke
    assert run_consecutive(5, **hooks) == 1
    assert calls["n"] == 2


def test_one_journey_fails_closed_when_a8_is_red():
    hooks = _hooks()
    hooks["ready_fn"] = lambda _s: Check("A8", False, "503")
    assert run_one_journey(**hooks) == 1


