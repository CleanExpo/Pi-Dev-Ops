class _Resp:
    def __init__(self, status: int, body: str) -> None:
        self.status = status
        self._body = body.encode()

    def read(self) -> bytes:
        return self._body

    def __enter__(self):
        return self

    def __exit__(self, *_a) -> bool:
        return False


class FakeOpener:
    def __init__(self, mapping: dict[str, tuple[int, str]]) -> None:
        self.mapping = mapping

    def open(self, req: Request, timeout: int = 15):
        url = req.full_url
        for suffix, (code, body) in self.mapping.items():
            if url.endswith(suffix):
                if code >= 400:
                    raise HTTPError(url, code, "err", hdrs=None, fp=io.BytesIO(body.encode()))
                return _Resp(code, body)
        raise HTTPError(url, 404, "missing", hdrs=None, fp=io.BytesIO(b""))


