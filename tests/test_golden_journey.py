def test_a8_passes_on_health_ready_200():
    opener = FakeOpener({"/api/health/ready": (200, '{"ok":true}')})
    check = probe_ready(opener, "https://example.test")
    assert check.ok is True
    assert "/api/health/ready" in check.detail


def test_a8_falls_through_404_to_ready_alias():
    opener = FakeOpener({"/api/health/ready": (404, ""), "/ready": (200, "ok")})
    check = probe_ready(opener, "https://example.test")
    assert check.ok is True
    assert check.detail.startswith("/ready")


def test_a8_fails_on_503():
    opener = FakeOpener({"/api/health/ready": (503, "clone failed")})
    check = probe_ready(opener, "https://example.test")
    assert check.ok is False
    assert "503" in check.detail


