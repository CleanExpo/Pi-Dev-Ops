def test_ladder_ignores_every_tao_cheap_knob(monkeypatch):
    """The Kimi bill came from TAO_CHEAP_REMOTE_MODEL. This role no longer reads it."""
    monkeypatch.setenv("TAO_CHEAP_PROVIDER", "openrouter")
