#!/usr/bin/env python3
"""board.py: the ticket board the cloudroom-router reads and writes. Stdlib only.

    board.py [--tickets specs/tickets] validate
    board.py [--tickets ...] next [--cap N] [--json]
    board.py [--tickets ...] set <id> <status> [--worker thr_...]
    board.py [--tickets ...] approve <id>        # the HUMAN's action (see below)
    board.py [--tickets ...] render              # regenerate board.md, a view nobody reads back

Exit codes: 0 ok, 1 the board or the requested change is refused (reasons printed),
2 it could not be read or written at all. A board that cannot be read is never "no work":
`next` on an unreadable or invalid board prints nothing on stdout and exits non-zero.

ONE WRITER PER FILE. Two writers (a human in an editor, the router through this script) on one
shared file can always lose an edit: an editor honours no lock, so no lock and no hash check
can close the window. So nothing here is shared:

  specs/tickets/NNN-slug/prd.md      human writes, front matter holds `mode:` and `runs:`
  specs/tickets/NNN-slug/eval.md     human writes
  specs/tickets/NNN-slug/APPROVED    HUMAN creates it (by hand, or `approve`). This script never
                                     deletes it and never writes it, except `approve`'s exclusive
                                     create. Without it a ticket is a draft.
  specs/tickets/NNN-slug/status      ROUTER writes it, only through `set`: one line,
                                     `<ready|doing|review|done|blocked> [worker=thr_x] [was=<state>]`
  specs/tickets/board.md             GENERATED by `render`. Never read back as state.

A ticket's status is its status file, else `ready` if APPROVED exists, else `draft`.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import tempfile
import time
from pathlib import Path

STATUSES = ["draft", "ready", "doing", "review", "done", "blocked"]
STORED = ["ready", "doing", "review", "done", "blocked"]        # what a status file may say
RESUMABLE = ["ready", "doing", "review"]                         # what a blocked ticket can remember
MODES = ["solo", "team"]
DIR_RE = re.compile(r"^(\d{3,})-([a-z0-9]+(?:-[a-z0-9]+)*)$")
WORKER_RE = re.compile(r"^[A-Za-z0-9_-]+$")
AFTER_RE = re.compile(r"^after\s+(\d{3,}(?:\s*,\s*\d{3,})*)\s*:\s*\S")
APPROVED = "APPROVED"
STATUS = "status"
VIEW = "board.md"

# Every move the router may make. draft is not a state it can leave: only the human's APPROVED does.
MOVES = {("ready", "doing"), ("doing", "review"), ("review", "doing"), ("review", "done"),
         ("doing", "doing")}                                    # doing -> doing = hand over to a new worker


class BoardUnreadable(Exception):
    """The tickets folder is missing or holds no tickets. Distinct from 'valid and empty'."""


class Board:
    def __init__(self, root: Path, tickets: list[dict], problems: list[str]):
        self.root = root
        self.tickets = tickets
        self.problems = problems          # found while reading (malformed files)

    def get(self, tid: str) -> dict | None:
        return next((t for t in self.tickets if t["id"] == tid), None)


def parse_front_matter(text: str) -> dict[str, str] | None:
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return None
    out: dict[str, str] = {}
    for ln in lines[1:]:
        if ln.strip() == "---":
            return out
        if ":" in ln:
            k, v = ln.split(":", 1)
            out[k.strip().lower()] = v.strip()
    return None


def parse_status(text: str) -> tuple[str, str, str]:
    """(state, worker, was) from a status file. ValueError when it is not one clean line."""
    lines = [ln for ln in text.split("\n") if ln.strip()]
    if len(lines) != 1:
        raise ValueError("must be exactly one line")
    parts = lines[0].split()
    if parts[0] not in STORED:
        raise ValueError(f"'{parts[0]}' is not one of {'|'.join(STORED)}")
    worker = was = ""
    for p in parts[1:]:
        k, _, v = p.partition("=")
        if k == "worker" and v:
            worker = v
        elif k == "was" and v:
            was = v
        else:
            raise ValueError(f"unexpected '{p}'")
    return parts[0], worker, was


def format_status(state: str, worker: str, was: str) -> str:
    return " ".join([state] + ([f"worker={worker}"] if worker else []) + ([f"was={was}"] if was else [])) + "\n"


def deps_of(runs: str) -> list[str] | None:
    """Ticket ids a `runs` value waits on. [] for 'alongside'; None when malformed."""
    runs = runs.strip()
    if runs.lower() == "alongside":
        return []
    m = AFTER_RE.match(runs)
    return [d.strip() for d in m.group(1).split(",")] if m else None


def load(root: Path) -> Board:
    if not root.is_dir():
        raise BoardUnreadable(f"{root} is not a folder")
    try:
        names = sorted(p.name for p in root.iterdir() if p.is_dir() and re.match(r"^\d+-", p.name))
    except OSError as e:
        raise BoardUnreadable(f"cannot list {root}: {e}")
    if not names:
        raise BoardUnreadable(f"no ticket folders (NNN-slug) in {root}; wrong path?")
    tickets: list[dict] = []
    problems: list[str] = []
    for name in names:
        folder = root / name
        m = DIR_RE.match(name)
        t = {"folder": folder, "id": m.group(1) if m else name.split("-")[0], "slug": m.group(2) if m else name,
             "mode": "", "runs": "", "approved": (folder / APPROVED).is_file(),
             "state": "", "worker": "", "was": "", "name": name}
        if not m:
            problems.append(f"{name}: folder must be <3+ digit id>-<lowercase-slug>")
        for fname in ("prd.md", "eval.md"):
            f = folder / fname
            try:
                body = f.read_text(encoding="utf-8")
            except OSError:
                body = ""
            if not body.strip():
                problems.append(f"{t['id']}: {name}/{fname} is missing or empty")
            elif fname == "prd.md":
                fm = parse_front_matter(body)
                if fm is None:
                    problems.append(f"{t['id']}: {name}/prd.md has no front matter (--- mode: ... runs: ... ---)")
                else:
                    t["mode"], t["runs"] = fm.get("mode", ""), fm.get("runs", "")
        sp = folder / STATUS
        if sp.exists():
            try:
                t["state"], t["worker"], t["was"] = parse_status(sp.read_text(encoding="utf-8"))
            except (OSError, ValueError) as e:
                problems.append(f"{t['id']}: {name}/status is malformed: {e}")
        tickets.append(t)
    for t in tickets:
        t["status"] = t["state"] or ("ready" if t["approved"] else "draft")
    return Board(root, tickets, problems)


def validate(board: Board) -> list[str]:
    errs = list(board.problems)
    ids = [t["id"] for t in board.tickets]
    graph: dict[str, list[str]] = {}
    for t in board.tickets:
        tid = t["id"]
        if ids.count(tid) > 1 and t is board.get(tid):
            errs.append(f"{tid}: duplicate id")
        if t["mode"] not in MODES:
            errs.append(f"{tid}: mode '{t['mode']}' is not one of {'|'.join(MODES)}")
        deps = deps_of(t["runs"])
        if deps is None:
            errs.append(f"{tid}: runs '{t['runs']}' must be 'alongside' or 'after NNN[, NNN]: reason'")
            deps = []
        for d in deps:
            if d not in ids:
                errs.append(f"{tid}: depends on {d}, which is not on the board")
            if d == tid:
                errs.append(f"{tid}: depends on itself")
        graph[tid] = [d for d in deps if d in ids]
        if t["worker"] and not WORKER_RE.match(t["worker"]):
            errs.append(f"{tid}: worker '{t['worker']}' is not a thread id")
        if t["state"]:
            if not t["approved"]:
                errs.append(f"{tid}: has a status file but no {APPROVED}; only the human approves a ticket")
            if t["state"] in ("doing", "review") and not t["worker"]:
                errs.append(f"{tid}: status {t['state']} needs a worker thread id")
            if t["state"] == "blocked":
                if t["was"] not in RESUMABLE:
                    errs.append(f"{tid}: blocked needs was=<{'|'.join(RESUMABLE)}>")
                elif t["was"] in ("doing", "review") and not t["worker"]:
                    errs.append(f"{tid}: blocked (was {t['was']}) needs its worker thread id")
            elif t["was"]:
                errs.append(f"{tid}: was= only belongs on a blocked ticket")
    errs.extend(_cycles(graph))
    return errs


def _cycles(graph: dict[str, list[str]]) -> list[str]:
    errs: set[str] = set()
    state: dict[str, int] = {}   # 1 = on the current path, 2 = finished

    def visit(n: str, path: list[str]) -> None:
        state[n] = 1
        for d in graph.get(n, []):
            if state.get(d) == 1:
                errs.add("dependency cycle: " + " -> ".join(path[path.index(d):] + [d]))
            elif d not in state:
                visit(d, path + [d])
        state[n] = 2

    for n in graph:
        if n not in state:
            visit(n, [n])
    return sorted(errs)


def ready_tickets(board: Board) -> list[dict]:
    done = {t["id"] for t in board.tickets if t["status"] == "done"}
    out = []
    for t in board.tickets:
        deps = deps_of(t["runs"])
        if t["approved"] and t["status"] == "ready" and deps is not None and all(d in done for d in deps):
            out.append(t)
    return out


def set_status(board: Board, tid: str, status: str, worker: str | None) -> tuple[str, str, str, str]:
    """Decide one transition. Returns (old, state, worker, was) to store. ValueError on refusal."""
    t = board.get(tid)
    if t is None:
        raise KeyError(tid)
    if status not in STORED:
        raise ValueError(f"status '{status}' is not one of {'|'.join(STORED)}")
    old = t["status"]
    if old == "draft":
        raise ValueError(f"not approved: only the human can approve a ticket (create {t['name']}/{APPROVED})")
    if old == "blocked":
        if status != t["was"]:
            raise ValueError(f"blocked (was {t['was']}) can only return to {t['was']}")
    elif status == "blocked":
        if old not in RESUMABLE:
            raise ValueError(f"{old} -> blocked is not allowed")
    elif (old, status) not in MOVES:
        raise ValueError(f"{old} -> {status} is not an allowed move")
    if worker is not None and not WORKER_RE.match(worker):
        raise ValueError(f"worker '{worker}' is not a thread id")
    w = worker or t["worker"]
    if status in ("doing", "review") and not w:
        raise ValueError(f"{status} needs --worker <thread id>")
    if status == "doing":
        done = {x["id"] for x in board.tickets if x["status"] == "done"}
        waiting = [d for d in (deps_of(t["runs"]) or []) if d not in done]
        if waiting:
            raise ValueError(f"waiting on {', '.join(waiting)}, which is not done")
    if status == "ready":
        w = ""
    return old, status, w, old if status == "blocked" else ""


def _write_atomic(path: Path, data: str) -> None:
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=".tmp-", suffix=".part")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def write_status(t: dict, state: str, worker: str, was: str) -> None:
    _write_atomic(t["folder"] / STATUS, format_status(state, worker, was))


def render_view(board: Board) -> str:
    rows = ["| id | slug | status | mode | runs | worker |", "|----|------|--------|------|------|--------|"]
    for t in board.tickets:
        status = f"blocked (was {t['was']})" if t["status"] == "blocked" else t["status"]
        rows.append(f"| {t['id']} | {t['slug']} | {status} | {t['mode']} | {t['runs']} | {t['worker']} |")
    return ("<!-- generated by board.py render - do not edit; nothing reads this file back. "
            f"Approve a ticket by creating {board.root.name}/NNN-slug/{APPROVED} -->\n\n# Ticket board\n\n"
            + "\n".join(rows) + "\n")


def write_view(board: Board) -> None:
    _write_atomic(board.root / VIEW, render_view(board))


def approve(root: Path, tid: str) -> str:
    """The one place this script writes APPROVED: an exclusive create, never an overwrite."""
    matches = [p for p in root.iterdir() if p.is_dir() and p.name.startswith(f"{tid}-")] if root.is_dir() else []
    if len(matches) != 1:
        raise KeyError(tid)
    target = matches[0] / APPROVED
    try:
        fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o644)
    except FileExistsError:
        return "already approved"
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(f"approved {time.strftime('%Y-%m-%dT%H:%M:%S%z')} by board.py approve\n")
    return "approved"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="board.py", description=__doc__.split("\n\n")[0])
    ap.add_argument("--tickets", default="specs/tickets")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("validate")
    sub.add_parser("render")
    nx = sub.add_parser("next")
    nx.add_argument("--cap", type=int, help="concurrency cap: list only as many as there are free slots")
    nx.add_argument("--json", action="store_true")
    st = sub.add_parser("set")
    st.add_argument("id")
    st.add_argument("status")
    st.add_argument("--worker")
    ap_ = sub.add_parser("approve", help="the human's action: creates NNN-slug/APPROVED, nothing else")
    ap_.add_argument("id")
    args = ap.parse_args(argv)
    root = Path(args.tickets)

    try:
        if args.cmd == "approve":
            try:
                print(f"{args.id}: {approve(root, args.id)}")
            except KeyError:
                print(f"UNKNOWN: no single ticket folder {args.id}-* in {root}", file=sys.stderr)
                return 2
            return 0
        board = load(root)
        errs = validate(board)
        if args.cmd == "validate":
            for e in errs:
                print(e)
            return 1 if errs else 0
        if errs:
            for e in errs:
                print(e, file=sys.stderr)
            print("REFUSED: board is invalid, nothing changed or dispatched", file=sys.stderr)
            return 1
        if args.cmd == "render":
            write_view(board)
            return 0
        if args.cmd == "next":
            picks = ready_tickets(board)
            if args.cap is not None:
                busy = sum(1 for t in board.tickets if t["status"] == "doing")
                picks = picks[:max(0, args.cap - busy)]
            if args.json:
                print(json.dumps([{"id": t["id"], "slug": t["slug"], "mode": t["mode"]} for t in picks]))
            else:
                for t in picks:
                    print(f"{t['id']} {t['slug']} {t['mode']}")
            return 0
        try:
            old, state, worker, was = set_status(board, args.id, args.status, args.worker)
        except KeyError:
            print(f"UNKNOWN: ticket {args.id} is not on the board", file=sys.stderr)
            return 2
        except ValueError as e:
            print(f"REFUSED: {args.id}: {e}", file=sys.stderr)
            return 1
        t = board.get(args.id)
        write_status(t, state, worker, was)
        print(f"{args.id}: {old} -> {state}")
        t.update(state=state, status=state, worker=worker, was=was)
        try:
            write_view(board)
        except OSError as e:
            print(f"warning: board.md view not regenerated ({e}); run `render`", file=sys.stderr)
        return 0
    except BoardUnreadable as e:
        print(f"UNKNOWN: {e}", file=sys.stderr)
        return 2
    except OSError as e:
        print(f"UNKNOWN: could not write under {root}: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
